export const BODYWEIGHT_CATALOG=groups.flatMap(([major,minor,names],g)=>names.split('|').map((name,i)=>({id:`bodyweight-default:${g}:${i}`,name,major,minor,seconds:60,description:supports[name]||'',tags:[minor,...(supports[name]?[supports[name]]:[]),...(minor==='광배근'?['대원근']:[])]})));
export function importBodyweightCatalog(record){
 if(record.bodyweightCatalogVersion===1)return record;
 const exercises=record.exercises||[];
 const normalize=x=>(x||'').replace(/\s/g,'').toLowerCase();
 const ids=new Set(exercises.map(x=>x.id));
 const names=new Set(exercises.map(x=>`${x.major}:${x.minor}:${normalize(x.name)}`));
 const incoming=BODYWEIGHT_CATALOG.filter(x=>!ids.has(x.id)&&!names.has(`${x.major}:${x.minor}:${normalize(x.name)}`));
 return {...record,exercises:[...exercises,...incoming],bodyweightCatalogVersion:1};
}
